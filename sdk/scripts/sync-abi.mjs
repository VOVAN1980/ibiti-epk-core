import fs from "node:fs";
import path from "node:path";

function readJson(p) {
  return JSON.parse(fs.readFileSync(p, "utf8"));
}

function ensureDir(p) {
  fs.mkdirSync(p, { recursive: true });
}

const ROOT = path.resolve(process.cwd(), ".."); // repo root
const OUT = path.join(ROOT, "out");

// typed ABIs as TypeScript constants (full viem type inference)
const v2 = [
  { name: "epkVaultAbi", in: path.join(OUT, "EPKVault.sol", "EPKVault.json") },
  { name: "dexGuardAbi", in: path.join(OUT, "DexGuard.sol", "DexGuard.json") },
  { name: "threatFeedGuardAbi", in: path.join(OUT, "ThreatFeedGuard.sol", "ThreatFeedGuard.json") },
  { name: "compositeGuardAbi", in: path.join(OUT, "CompositeGuard.sol", "CompositeGuard.json") },
  { name: "epkRegistryAbi", in: path.join(OUT, "EPKRegistry.sol", "EPKRegistry.json") },
  { name: "epkVaultFactoryAbi", in: path.join(OUT, "EPKVaultFactory.sol", "EPKVaultFactory.json") },
];
const v2Dir = path.join(process.cwd(), "src", "v2", "abi");
ensureDir(v2Dir);
for (const a of v2) {
  if (!fs.existsSync(a.in)) {
    console.error(`Missing artifact: ${a.in}`);
    process.exitCode = 1;
    continue;
  }
  const abi = readJson(a.in).abi;
  const file = path.join(v2Dir, `${a.name}.ts`);
  const from = path.relative(ROOT, a.in).split(path.sep).join("/");
  fs.writeFileSync(file, `// Generated by scripts/sync-abi.mjs from ${from} — do not edit.\nexport const ${a.name} = ${JSON.stringify(abi, null, 2)} as const;\n`);
  console.log(`OK: ${a.name} -> ${path.relative(process.cwd(), file)}`);
}

// creation bytecode of the guards, so integrators can deploy their own configuration from the SDK
const bytecodes = [
  { name: "dexGuardBytecode", in: path.join(OUT, "DexGuard.sol", "DexGuard.json") },
  { name: "threatFeedGuardBytecode", in: path.join(OUT, "ThreatFeedGuard.sol", "ThreatFeedGuard.json") },
  { name: "compositeGuardBytecode", in: path.join(OUT, "CompositeGuard.sol", "CompositeGuard.json") },
];
for (const a of bytecodes) {
  if (!fs.existsSync(a.in)) {
    console.error(`Missing artifact: ${a.in}`);
    process.exitCode = 1;
    continue;
  }
  const code = readJson(a.in).bytecode.object;
  const from = path.relative(ROOT, a.in).split(path.sep).join("/");
  const file = path.join(v2Dir, `${a.name}.ts`);
  fs.writeFileSync(file, `// Generated by scripts/sync-abi.mjs from ${from} — do not edit.
export const ${a.name} = "${code}" as const;
`);
  console.log(`OK: ${a.name} -> ${path.relative(process.cwd(), file)}`);
}

if (!process.exitCode) {
  console.log("ABI sync complete.");
}
